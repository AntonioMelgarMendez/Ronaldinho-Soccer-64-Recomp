#!/usr/bin/env python3
"""Discover reachable MIPS III code and emit an AOT dispatch unit.

This deliberately keeps an interpreter fallback: indirect calls and code loaded
later by the game's overlay system cannot be known from the initial ROM image.
Re-running this tool with additional --entry values grows AOT coverage.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import struct
from collections import deque
from pathlib import Path

ROM_BASE = 0x1000
RAM_BASE = 0x80000400
PAYLOAD_MAX = 0x100000


def normalize(data: bytearray) -> bytearray:
    magic = bytes(data[:4])
    if magic == bytes.fromhex("80371240"):
        return data
    if magic == bytes.fromhex("37804012"):
        for i in range(0, len(data) - 1, 2):
            data[i], data[i + 1] = data[i + 1], data[i]
        return data
    if magic == bytes.fromhex("40123780"):
        for i in range(0, len(data) - 3, 4):
            data[i:i + 4] = data[i:i + 4][::-1]
        return data
    raise ValueError("not a recognized N64 ROM")


def rom_offset(pc: int) -> int | None:
    off = ROM_BASE + (pc - RAM_BASE)
    return off if ROM_BASE <= off < ROM_BASE + PAYLOAD_MAX else None


def read_word(rom: bytes, pc: int) -> int | None:
    off = rom_offset(pc)
    if off is None or off + 4 > len(rom):
        return None
    return struct.unpack_from(">I", rom, off)[0]


def discover(rom: bytes, entries: list[int], limit: int) -> dict[int, int]:
    found: dict[int, int] = {}
    pending = deque(entries)
    queued = set(entries)
    while pending and len(found) < limit:
        pc = pending.popleft()
        constants: dict[int, int] = {0: 0}
        while pc not in found and len(found) < limit:
            ins = read_word(rom, pc)
            if ins is None:
                break
            found[pc] = ins
            op, fn = ins >> 26, ins & 63
            is_jump_reg = op == 0 and fn in (8, 9)
            is_jump = op in (2, 3)
            is_branch = op in (1, 4, 5, 6, 7, 20, 21, 22, 23)
            if is_jump or is_branch or is_jump_reg:
                delay = pc + 4
                delay_ins = read_word(rom, delay)
                if delay_ins is not None:
                    found.setdefault(delay, delay_ins)
                targets: list[int] = []
                if is_jump:
                    targets.append(((pc + 4) & 0xF0000000) | ((ins & 0x03FFFFFF) << 2))
                    if op == 3:
                        targets.append(pc + 8)
                elif is_branch:
                    imm = ins & 0xFFFF
                    if imm & 0x8000:
                        imm -= 0x10000
                    targets.extend((pc + 4 + imm * 4, pc + 8))
                elif is_jump_reg:
                    rs = (ins >> 21) & 31
                    if rs in constants:
                        targets.append(constants[rs] & 0xFFFFFFFF)
                for target in targets:
                    if target not in found and target not in queued and read_word(rom, target) is not None:
                        queued.add(target)
                        pending.append(target)
                break
            # Small constant propagation pass. SDK startup stubs commonly form
            # an absolute target with LUI/ADDIU and jump through a register.
            rs, rt = (ins >> 21) & 31, (ins >> 16) & 31
            if op == 0x0F:
                constants[rt] = ((ins & 0xFFFF) << 16) & 0xFFFFFFFF
            elif op in (0x08, 0x09) and rs in constants:
                imm = ins & 0xFFFF
                if imm & 0x8000:
                    imm -= 0x10000
                constants[rt] = (constants[rs] + imm) & 0xFFFFFFFF
            elif op == 0x0D and rs in constants:
                constants[rt] = constants[rs] | (ins & 0xFFFF)
            elif op != 0 or fn not in (0x00, 0x21, 0x25):
                if rt:
                    constants.pop(rt, None)
            pc += 4
    return found


def emit_cpp(found: dict[int, int], output: Path) -> None:
    lines = [
        '// Generated by tools/recompile.py; do not edit.\n',
        '#include "iss64/cpu.hpp"\n#include "iss64/memory.hpp"\n\n',
        'namespace iss64 {\nbool recomp_step(Cpu& cpu, Memory& memory) {\n',
        '    switch (cpu.pc) {\n',
    ]
    for pc, ins in sorted(found.items()):
        lines.append(f'    case 0x{pc:08X}u: execute_instruction(cpu, memory, 0x{ins:08X}u); return true;\n')
    lines.extend(['    default: return false;\n    }\n}\n} // namespace iss64\n'])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(''.join(lines))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("rom", type=Path)
    ap.add_argument("--entry", action="append", type=lambda x: int(x, 0), default=[])
    ap.add_argument("--limit", type=int, default=100_000)
    ap.add_argument("--output", type=Path, default=Path("generated/recomp.cpp"))
    ap.add_argument("--report", type=Path, default=Path("generated/report.json"))
    ap.add_argument("--profile", action="append", type=Path, default=[], help="merge runtime PC/instruction profile")
    args = ap.parse_args()

    raw = args.rom.read_bytes()
    sha1 = hashlib.sha1(raw).hexdigest()
    rom = bytes(normalize(bytearray(raw)))
    title = rom[0x20:0x34].decode("ascii", "replace").rstrip(" \0")
    entries = args.entry or [struct.unpack_from(">I", rom, 8)[0]]
    found = discover(rom, entries, args.limit)
    profile_instructions = 0
    for profile in args.profile:
        for line in profile.read_text().splitlines():
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            pc_text, ins_text = line.split()[:2]
            pc, ins = int(pc_text, 16), int(ins_text, 16)
            if pc not in found:
                profile_instructions += 1
            found[pc] = ins
    emit_cpp(found, args.output)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps({
        "title": title, "sha1": sha1, "rom_size": len(rom),
        "entries": [f"0x{x:08X}" for x in entries],
        "translated_instructions": len(found),
        "profile_instructions": profile_instructions,
        "lowest_pc": f"0x{min(found):08X}" if found else None,
        "highest_pc": f"0x{max(found):08X}" if found else None,
    }, indent=2) + "\n")
    print(f"{title}: emitted {len(found)} instructions to {args.output}")


if __name__ == "__main__":
    main()
